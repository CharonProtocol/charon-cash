// Writes lib/commitments.ts: real Poseidon commitments for dummy notes.
// commitment = poseidon(amount, pubkey, blinding, mintField), as in sdk/src/crypto.ts.
// Run from charon/: node scripts/commitments.mjs

import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(fileURLToPath(new URL("../../sdk/package.json", import.meta.url)));
const { WasmFactory } = await import(require.resolve("@lightprotocol/hasher.rs"));

const wasm = await WasmFactory.getInstance();
const h = (inputs) => wasm.poseidonHashString(inputs);
const SOL_MINT_FIELD = "11111111111111111111111111111112";

const hex = (dec) => "0x" + BigInt(dec).toString(16).padStart(64, "0");

function note(i) {
  const privkey = String(1_000_003n * BigInt(i + 7) + 424_242n);
  const pubkey = h([privkey]);
  const amount = String((i % 9) * 125_000_000 + 10_000_000);
  const blinding = String(900_000_001 + i * 7_919);
  return h([amount, pubkey, blinding, SOL_MINT_FIELD]);
}

const commitments = Array.from({ length: 48 }, (_, i) => hex(note(i)));

const leaves = Array.from({ length: 8 }, (_, i) => note(100 + i));
const levels = [leaves];
while (levels.at(-1).length > 1) {
  const prev = levels.at(-1);
  const next = [];
  for (let i = 0; i < prev.length; i += 2) next.push(h([prev[i], prev[i + 1]]));
  levels.push(next);
}
const tree = levels.map((row) => row.map(hex));

const out = `// Generated by scripts/commitments.mjs. Dummy notes; real Poseidon outputs.

export const COMMITMENTS = ${JSON.stringify(commitments, null, 2)} as const;

/** Leaves first, root last. */
export const TREE = ${JSON.stringify(tree, null, 2)} as const;
`;

writeFileSync(new URL("../lib/commitments.ts", import.meta.url), out);
console.log(`wrote ${commitments.length} commitments, tree root ${tree.at(-1)[0]}`);
