export type Token = "SOL" | "USDC" | "USDT";

export function TokenIcon({
  token = "SOL",
  className = "size-6 shrink-0",
}: {
  token?: Token;
  className?: string;
}) {
  const uid = useId().replace(/:/g, "");
  if (token === "USDC") {
    return (
      <UsdcIcon
        uid={uid}
        className={className}
      />
    );
  }
  if (token === "USDT") {
    return (
      <UsdtIcon
        uid={uid}
        className={className}
      />
    );
  }
  return (
    <SolIcon
      uid={uid}
      className={className}
    />
  );
}

